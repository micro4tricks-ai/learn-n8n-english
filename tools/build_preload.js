// Writes <link rel="preload" as="script"> for every local script of a page (between <!-- preload --> markers,
// right after the CSP block). The pages load their scripts in order with plain <script src>, and the inline
// I18N.en() call (document.write) stops the browser's look-ahead, so without these hints the files came one
// after another: 30 files on tips.html took 6 s on a slow phone. Preloaded, they download together and still
// run in the same order. Run by npm run build (after build_csp, before build_sw).
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const pages = fs.readdirSync(ROOT).filter(f => f.endsWith('.html') && f !== 'run.html').sort();
const RE = /<!-- preload:[\s\S]*?<!-- \/preload -->\n/;
let n = 0;
pages.forEach(f => {
  const p = path.join(ROOT, f);
  let html = fs.readFileSync(p, 'utf8');
  const srcs = [...new Set([...html.replace(RE, '').matchAll(/<script src="([^"]+)"/g)].map(m => m[1]).filter(s => !/^(https?:)?\/\//.test(s)))];
  const block = '<!-- preload: generated by tools/build_preload.js -->\n' +
    srcs.map(s => '<link rel="preload" href="' + s + '" as="script">\n').join('') + '<!-- /preload -->\n';
  if(RE.test(html)) html = html.replace(RE, block);
  else if(/<!-- \/csp -->\n/.test(html)) html = html.replace(/(<!-- \/csp -->\n)/, '$1' + block);
  else { console.error(f + ': no CSP block to put the preload hints after'); process.exitCode = 1; return; }
  fs.writeFileSync(p, html);
  n += srcs.length;
});
console.log('preload: ' + n + ' script hints on ' + pages.length + ' pages');
