// Sharing and search-engine metadata for every page, from its own <title> and description:
// canonical link, Open Graph and Twitter card tags (between <!-- meta --> markers in each page), plus
// sitemap.xml (submit it in Google Search Console; a robots.txt only works at the domain root). Run by npm run build.
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://micro4tricks-ai.github.io/learn-n8n-english/';
const IMAGE = SITE + 'docs/social-preview.png';
const esc = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const pages = fs.readdirSync(ROOT).filter(f => f.endsWith('.html')).sort((a, b) => a === 'index.html' ? -1 : b === 'index.html' ? 1 : a.localeCompare(b));
pages.forEach(f => {
  const p = path.join(ROOT, f);
  let html = fs.readFileSync(p, 'utf8');
  const title = (html.match(/<title>([^<]*)<\/title>/) || [])[1] || 'رحلة المبرمج';
  const desc = (html.match(/<meta name="description" content="([^"]*)"/) || [])[1] || '';
  const url = SITE + (f === 'index.html' ? '' : f);
  const block = '<!-- meta: generated by tools/build_meta.js -->\n' + [
    '<link rel="canonical" href="' + url + '">',
    '<meta property="og:type" content="website">',
    '<meta property="og:site_name" content="رحلة المبرمج · Developer Journey">',
    '<meta property="og:title" content="' + esc(title) + '">',
    '<meta property="og:description" content="' + esc(desc) + '">',
    '<meta property="og:url" content="' + url + '">',
    '<meta property="og:image" content="' + IMAGE + '">',
    '<meta property="og:image:width" content="1280">',
    '<meta property="og:image:height" content="640">',
    '<meta property="og:locale" content="ar_EG">',
    '<meta property="og:locale:alternate" content="en_US">',
    '<meta name="twitter:card" content="summary_large_image">'
  ].join('\n') + '\n<!-- /meta -->\n';
  if(/<!-- meta:[\s\S]*?<!-- \/meta -->\n/.test(html)) html = html.replace(/<!-- meta:[\s\S]*?<!-- \/meta -->\n/, block);
  else html = html.replace(/(<meta name="description"[^>]*>\n)/, '$1' + block);
  fs.writeFileSync(p, html);
});
fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  pages.map(f => '  <url><loc>' + SITE + (f === 'index.html' ? '' : f) + '</loc></url>').join('\n') + '\n</urlset>\n');
console.log('meta: ' + pages.length + ' pages + sitemap.xml');
