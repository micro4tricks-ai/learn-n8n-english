// Builds assets/js/<page>-en.js from the frozen key lists and the translation parts.
//   tools/i18n/<page>-keys.json   – Arabic source strings, in a fixed order
//   tools/i18n/<page>-NN.json     – {"index": "English"} translation parts
// usage: node tools/make_dicts.js [--freeze]   (--freeze copies tools/missing-*.json to *-keys.json)
const fs = require('fs');
const path = require('path');
const DIR = path.join(__dirname, 'i18n');
const OUT = path.join(__dirname, '..', 'assets', 'js');
const pages = ['common', 'n8n', 'english'];
if (process.argv.includes('--freeze')) {
  pages.forEach(p => {
    const keysFile = path.join(DIR, `${p}-keys.json`);
    const fresh = JSON.parse(fs.readFileSync(path.join(__dirname, `missing-${p}.json`), 'utf8'));
    const old = fs.existsSync(keysFile) ? JSON.parse(fs.readFileSync(keysFile, 'utf8')) : [];
    const merged = old.concat(fresh.filter(k => !old.includes(k)));   // only append, never reorder
    fs.writeFileSync(keysFile, JSON.stringify(merged, null, 1));
    console.log(p, 'keys', merged.length, '(+' + (merged.length - old.length) + ')');
  });
}
let ok = true;
pages.forEach(p => {
  const keys = JSON.parse(fs.readFileSync(path.join(DIR, `${p}-keys.json`), 'utf8'));
  const tr = {};
  fs.readdirSync(DIR).filter(f => new RegExp(`^${p}-\\d+\\.json$`).test(f)).sort().forEach(f => {
    Object.assign(tr, JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')));
  });
  const dict = {};
  const missing = [];
  keys.forEach((k, i) => { if (tr[i] == null) missing.push(i); else dict[k] = tr[i]; });
  if (missing.length) { ok = false; console.log(p, 'MISSING indexes:', missing.slice(0, 30).join(','), missing.length > 30 ? '…' : ''); }
  fs.writeFileSync(path.join(OUT, `${p}-en.js`),
    `// English dictionary for ${p} (generated by tools/make_dicts.js — edit tools/i18n/${p}-NN.json instead)\n` +
    `window.I18N_ADD && I18N_ADD(${JSON.stringify(dict, null, 1)});\n`);
  console.log(p, Object.keys(dict).length + '/' + keys.length, 'translated');
});
process.exit(ok ? 0 : 1);
