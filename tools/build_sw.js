// Writes sw.js (the offline app) with the current asset version and two lists of this site's files:
//   FILES — the shell every page shares (pages, styles, core scripts, icons): kept on the first visit
//   LAZY  — each page's own data and scripts: kept the first time they are used, or all at once when the
//           learner presses «Download for offline» on the review page (with the 48 week files)
// This keeps the first visit light (about 150 KB compressed instead of 1 MB). Run by npm run build.
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const pages = fs.readdirSync(ROOT).filter(f => f.endsWith('.html')).sort();
const all = new Set(['./', 'manifest.webmanifest', 'assets/icons/icon-192.png', 'assets/icons/icon-512.png', 'assets/favicon.svg', 'assets/logo.svg']);
let version = '';
pages.forEach(p => {
  all.add(p);
  const html = fs.readFileSync(path.join(ROOT, p), 'utf8');
  for(const m of html.matchAll(/(?:src|href)="([^"#:]+?)"/g)){
    const u = m[1];
    if(/^(https?:)?\/\//.test(u) || u.endsWith('.html') || /['\s+]/.test(u)) continue;   // skip remote links, pages and code inside inline scripts
    all.add(u);
    const v = u.match(/\?v=(\w+)/); if(v) version = v[1];
  }
});
// files a script loads on demand (not named in any page): the search index, the review deck, the lab's sql.js
['assets/data/search-index.js', 'assets/data/deck.js', 'assets/js/vendor/sqljs/sql-wasm.js', 'assets/js/vendor/sqljs/sql-wasm.wasm'].forEach(f => all.add(f + '?v=' + version));
[...all].forEach(f => { const p = f.split('?')[0]; if(p !== './' && !fs.existsSync(path.join(ROOT, p))) { console.error('missing file: ' + p); process.exitCode = 1; } });
// the shared shell: pages, the stylesheet, icons and the scripts every page loads
const SHELL = /^(\.\/|[\w-]+\.html|manifest\.webmanifest|assets\/(icons\/|favicon|logo|css\/site\.css)|assets\/js\/(i18n|common-en|site|sections|ui|account|config)\.js|assets\/js\/vendor\/supabase\.js|content\/pages\.js)/;
const files = [...all].filter(f => SHELL.test(f)).sort(), lazy = [...all].filter(f => !SHELL.test(f)).sort();
const size = list => list.reduce((n, f) => n + (f === './' ? 0 : fs.statSync(path.join(ROOT, f.split('?')[0])).size), 0);
const tpl = fs.readFileSync(path.join(__dirname, 'sw.template.js'), 'utf8');
fs.writeFileSync(path.join(ROOT, 'sw.js'), '// Generated by tools/build_sw.js from tools/sw.template.js — do not edit.\n' +
  tpl.replace('__VERSION__', version).replace('__FILES__', JSON.stringify(files, null, 1)).replace('__LAZY__', JSON.stringify(lazy, null, 1)));
console.log('sw.js: version ' + version + ', ' + files.length + ' shell files (' + Math.round(size(files) / 1024) + ' KB) kept on the first visit, ' +
  lazy.length + ' more (' + Math.round(size(lazy) / 1024) + ' KB) when used or downloaded for offline');
