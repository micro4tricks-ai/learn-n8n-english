// Writes sw.js (the offline app) with the current asset version and the list of files to keep offline:
// every page and every local file the pages load. Week files are cached when opened (or all at once
// from the review page). Run after bumping ?v= (npm run build does it).
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const pages = fs.readdirSync(ROOT).filter(f => f.endsWith('.html')).sort();
const files = new Set(['./', 'manifest.webmanifest', 'assets/icons/icon-192.png', 'assets/icons/icon-512.png', 'assets/favicon.svg', 'assets/logo.svg']);
let version = '';
pages.forEach(p => {
  files.add(p);
  const html = fs.readFileSync(path.join(ROOT, p), 'utf8');
  for(const m of html.matchAll(/(?:src|href)="([^"#:]+?)"/g)){
    const u = m[1];
    if(/^(https?:)?\/\//.test(u) || u.endsWith('.html') || /['\s+]/.test(u)) continue;   // skip remote links, pages and code inside inline scripts
    files.add(u);
    const v = u.match(/\?v=(\w+)/); if(v) version = v[1];
  }
});
['assets/data/search-index.js', 'assets/data/deck.js'].forEach(f => files.add(f + '?v=' + version));
[...files].forEach(f => { const p = f.split('?')[0]; if(p !== './' && !fs.existsSync(path.join(ROOT, p))) { console.error('missing file: ' + p); process.exitCode = 1; } });
const tpl = fs.readFileSync(path.join(__dirname, 'sw.template.js'), 'utf8');
fs.writeFileSync(path.join(ROOT, 'sw.js'), '// Generated by tools/build_sw.js from tools/sw.template.js — do not edit.\n' +
  tpl.replace('__VERSION__', version).replace('__FILES__', JSON.stringify([...files].sort(), null, 1)));
console.log('sw.js: version ' + version + ', ' + files.size + ' files precached');
