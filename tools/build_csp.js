// Writes a Content-Security-Policy <meta> into every page (between <!-- csp --> markers, right after <meta charset>).
// GitHub Pages can't send headers, so the policy lives in the page. It allows this site's own scripts, the inline
// scripts of each page by their SHA-256 hash, and only the outside services the site uses; injected markup can't
// run script, load a remote script or post a form anywhere. run.html (the sandboxed code runner) gets none: it has
// no origin of its own and runs the learner's code. Run by npm run build (after build_meta, before build_sw).
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.resolve(__dirname, '..');
const cfg = fs.readFileSync(path.join(ROOT, 'assets/js/config.js'), 'utf8');
const supa = (cfg.match(/url:\s*'(https:\/\/[a-z0-9]+\.supabase\.co)'/) || [])[1];
const goat = (cfg.match(/goatcounter:\s*'([a-z0-9-]+)'/) || [])[1];
const sha = s => "'sha256-" + crypto.createHash('sha256').update(s, 'utf8').digest('base64') + "'";
const pages = fs.readdirSync(ROOT).filter(f => f.endsWith('.html') && f !== 'run.html').sort();
pages.forEach(f => {
  const p = path.join(ROOT, f);
  let html = fs.readFileSync(p, 'utf8');
  const inline = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m => sha(m[1]));
  const lab = f === 'lab.html';   // the SQL playground runs sql.js (WebAssembly from jsDelivr) on the page itself
  const policy = [
    "default-src 'self'",
    ["script-src 'self'"].concat(inline, ['https://giscus.app'], goat ? ['https://gc.zgo.at'] : [], lab ? ['https://cdn.jsdelivr.net', "'wasm-unsafe-eval'"] : []).join(' '),
    "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
    "font-src 'self' https://fonts.gstatic.com",
    "img-src 'self' data: blob: https:",
    "media-src 'self' blob: data:",
    ["connect-src 'self'"].concat(supa ? [supa, supa.replace('https:', 'wss:')] : [], ['https://api.n8n.io', 'https://giscus.app', 'https://cdn.jsdelivr.net'], goat ? ['https://' + goat + '.goatcounter.com'] : []).join(' '),
    "frame-src 'self' https://giscus.app",
    "worker-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "manifest-src 'self'"
  ].join('; ');
  const block = '<!-- csp: generated by tools/build_csp.js -->\n<meta http-equiv="Content-Security-Policy" content="' + policy + '">\n' +
    '<meta name="referrer" content="strict-origin-when-cross-origin">\n<!-- /csp -->\n';
  if(/<!-- csp:[\s\S]*?<!-- \/csp -->\n/.test(html)) html = html.replace(/<!-- csp:[\s\S]*?<!-- \/csp -->\n/, block);
  else if(/<meta charset="utf-8">\n/i.test(html)) html = html.replace(/(<meta charset="utf-8">\n)/i, '$1' + block);
  else { console.error(f + ': no <meta charset="utf-8"> line to put the policy after'); process.exitCode = 1; return; }
  fs.writeFileSync(p, html);
});
console.log('csp: ' + pages.length + ' pages');
